void GerarNovaSemente(void) {
    for (int y = 0; y < 16; y++) {
        for (int x = 0; x < 16; x++) {
            SeedLayout[x][y] = (x + y) % 8 | (Seq[(x + y) & 3] << 3);
        }
    }
}

void BakeDungeon(void) {
    for (int salaY = 0; salaY < 4; salaY++) {
        for (int salaX = 0; salaX < 4; salaX++) {
            int layoutBase = (salaX + salaY) % 8;
            int rot = Seq[(salaX + salaY) & 3];
            int bit0 = rot & 1, bit1 = rot >> 1;
            int invX = 15 * bit1, invY = 15 * (bit0 ^ bit1);
            for (int tileY = 0; tileY < 16; tileY++) {
                for (int tileX = 0; tileX < 16; tileX++) {
                    int rx = bit0 ? tileY : tileX;
                    int ry = bit0 ? tileX : tileY;
                    if (bit1) rx = invX - rx;
                    if (bit0 ^ bit1) ry = invY - ry;
                    int tileLido = MasmorraLayouts[layoutBase][ry][rx];
                    if (tileLido > 1 && tileLido <= 5) {
                        tileLido = 2 + (((tileLido - 2) + rot) & 3);
                    }
                    Dungeon[(((salaY << 4) + tileY) << 6) + ((salaX << 4) + tileX)] = tileLido;
                }
            }
        }
    }
}

unsigned char CelulaMundo(int mundoX, int mundoY) {
    return Dungeon[((mundoY & 0x3F0) << 2) + ((mundoX >> 4) & 0x3F)];
}
